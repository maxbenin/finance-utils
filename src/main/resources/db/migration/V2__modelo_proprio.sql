-- Fase 2: o app passa a ter os próprios dados. O Dinzo (e, depois, arquivos OFX/CSV/XLSX/PDF)
-- vira apenas uma origem, registrada como referência externa.
-- Registros vindos do Dinzo reaproveitam o uuid do Dinzo como id próprio; os demais recebem um uuid novo.

CREATE TABLE account (
    id                        VARCHAR(36)  PRIMARY KEY,
    name                      VARCHAR(200) NOT NULL,
    kind                      VARCHAR(20)  NOT NULL,     -- CHECKING | CREDIT_CARD
    institution               VARCHAR(200),
    tracked                   BOOLEAN      NOT NULL DEFAULT TRUE,
    bill_paid_from_account_id VARCHAR(36)  REFERENCES account (id),  -- cartão: conta que paga a fatura
    created_at                TIMESTAMP    NOT NULL
);

CREATE TABLE account_ref (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   VARCHAR(36)  NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    source       VARCHAR(20)  NOT NULL,                   -- DINZO | OFX | ...
    external_id  VARCHAR(200) NOT NULL,
    CONSTRAINT uk_account_ref UNIQUE (source, external_id)
);

CREATE TABLE category (
    id          VARCHAR(36)  PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    parent_id   VARCHAR(36)  REFERENCES category (id),
    color_hex   VARCHAR(8),
    archived    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE category_ref (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  VARCHAR(36)  NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    source       VARCHAR(20)  NOT NULL,
    external_id  VARCHAR(200) NOT NULL,
    CONSTRAINT uk_category_ref UNIQUE (source, external_id)
);

CREATE TABLE txn (
    id                     VARCHAR(36)    PRIMARY KEY,
    account_id             VARCHAR(36)    NOT NULL REFERENCES account (id),
    txn_date               DATE           NOT NULL,     -- data da compra (competência)
    direction              VARCHAR(10)    NOT NULL,     -- DEBIT | CREDIT
    status                 VARCHAR(10)    NOT NULL,     -- PENDING | POSTED
    amount                 NUMERIC(14, 2) NOT NULL,
    description            VARCHAR(500),
    original_description   VARCHAR(500),
    notes                  VARCHAR(1000),
    category_id            VARCHAR(36)    REFERENCES category (id),
    card_final             VARCHAR(8),
    installment_current    INT,
    installment_total      INT,
    recurrence_ref         VARCHAR(64),
    manual                 BOOLEAN        NOT NULL DEFAULT FALSE,
    origin                 VARCHAR(20)    NOT NULL,     -- APP | DINZO | OFX | CSV | XLSX | PDF
    bill_payment           BOOLEAN        NOT NULL DEFAULT FALSE,
    transfer_group_ref     VARCHAR(64),                 -- grupo de transferência informado pela origem
    created_at             TIMESTAMP      NOT NULL,
    updated_at             TIMESTAMP      NOT NULL,
    removed_at             TIMESTAMP,

    -- Calculado pelo processamento
    kind                   VARCHAR(20),
    nature                 VARCHAR(10),
    profile_id             BIGINT REFERENCES profile (id),
    subprofile_id          BIGINT REFERENCES profile (id),
    assignment_rule        VARCHAR(40),
    contributor            VARCHAR(80),
    counterpart_profile_id BIGINT REFERENCES profile (id),
    transfer_pair_id       VARCHAR(36),
    auto_exclude_reason    VARCHAR(200),

    -- Decisões do usuário
    totals_override        VARCHAR(10),                 -- EXCLUDE | INCLUDE
    exclude_reason         VARCHAR(200),
    profile_override_id    BIGINT REFERENCES profile (id),
    superfluous            BOOLEAN,
    merged_into_id         VARCHAR(36)
);

CREATE INDEX ix_txn_date    ON txn (txn_date);
CREATE INDEX ix_txn_account ON txn (account_id, txn_date);
CREATE INDEX ix_txn_profile ON txn (profile_id, txn_date);

CREATE TABLE txn_tag (
    txn_id  VARCHAR(36) NOT NULL REFERENCES txn (id) ON DELETE CASCADE,
    tag     VARCHAR(80) NOT NULL,
    PRIMARY KEY (txn_id, tag)
);

-- De onde cada lançamento veio; um mesmo lançamento pode ter várias referências
CREATE TABLE txn_ref (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id         VARCHAR(36)  NOT NULL REFERENCES txn (id) ON DELETE CASCADE,
    source         VARCHAR(20)  NOT NULL,
    external_id    VARCHAR(200) NOT NULL,
    raw_data       TEXT         NOT NULL,
    content_hash   VARCHAR(64)  NOT NULL,
    first_seen_at  TIMESTAMP    NOT NULL,
    last_seen_at   TIMESTAMP    NOT NULL,
    changed_at     TIMESTAMP,
    removed_at     TIMESTAMP,
    CONSTRAINT uk_txn_ref UNIQUE (source, external_id)
);

CREATE TABLE txn_reconciliation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_id   VARCHAR(36)   NOT NULL REFERENCES txn (id),
    real_id     VARCHAR(36)   NOT NULL REFERENCES txn (id),
    score       NUMERIC(5, 3) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    decided_at  TIMESTAMP,
    CONSTRAINT uk_txn_reconciliation UNIQUE (manual_id, real_id)
);

