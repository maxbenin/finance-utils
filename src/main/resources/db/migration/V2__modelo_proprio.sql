INSERT INTO account (id, name, kind, tracked, created_at)
SELECT dinzo_id, title,
       CASE WHEN account_type = 'CREDIT' THEN 'CREDIT_CARD' ELSE 'CHECKING' END,
       tracked, COALESCE(last_synced_at, CURRENT_TIMESTAMP)
FROM dinzo_account;

-- Lançamentos de contas que nunca foram espelhadas (não deveria acontecer)
INSERT INTO account (id, name, kind, tracked, created_at)
SELECT DISTINCT e.account_id, '(conta sem cadastro)', 'CHECKING', TRUE, CURRENT_TIMESTAMP
FROM ledger_entry e
WHERE NOT EXISTS (SELECT 1 FROM account a WHERE a.id = e.account_id);

INSERT INTO account_ref (account_id, source, external_id)
SELECT id, 'DINZO', id FROM account WHERE name <> '(conta sem cadastro)';

INSERT INTO txn (id, account_id, txn_date, direction, status, amount, description, original_description,
                 card_final, installment_current, installment_total, recurrence_ref, manual, origin,
                 bill_payment, transfer_group_ref, created_at, updated_at, removed_at, superfluous, merged_into_id)
SELECT dinzo_id, account_id, entry_date, direction, status, amount, description, original_description,
       card_final, installment_current, installment_total, recurrence_id, source = 'APP_MANUAL', 'DINZO',
       bill_to_account_id IS NOT NULL, transfer_group_id, first_seen_at, COALESCE(changed_at, first_seen_at),
       removed_at, superfluous, merged_into_id
FROM ledger_entry;

INSERT INTO txn_tag (txn_id, tag)
SELECT dinzo_id, tag FROM ledger_entry_tag;

INSERT INTO txn_ref (txn_id, source, external_id, raw_data, content_hash, first_seen_at, last_seen_at,
                     changed_at, removed_at)
SELECT dinzo_id, 'DINZO', dinzo_id, raw_json, content_hash, first_seen_at, last_seen_at, changed_at, removed_at
FROM ledger_entry;

INSERT INTO txn_reconciliation (manual_id, real_id, score, status, created_at, decided_at)
SELECT manual_id, real_id, score, status, created_at, decided_at FROM reconciliation;

DROP TABLE reconciliation;
DROP TABLE ledger_entry_tag;
DROP TABLE ledger_entry;
DROP TABLE dinzo_account;
