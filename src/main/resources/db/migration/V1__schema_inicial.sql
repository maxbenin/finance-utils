-- Perfis (Max, Familia) e subperfis (ex.: Pedro dentro de Familia)
CREATE TABLE profile (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL UNIQUE,
    parent_id   BIGINT REFERENCES profile (id),
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Regras de atribuição: final de cartão, conta Dinzo ou tag -> perfil
CREATE TABLE profile_rule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_type   VARCHAR(20)  NOT NULL,          -- CARD_FINAL | ACCOUNT | TAG
    match_value VARCHAR(120) NOT NULL,          -- "1234", uuid da conta, título da tag
    profile_id  BIGINT       NOT NULL REFERENCES profile (id),
    card_user   VARCHAR(80),                    -- quem usa o cartão (só CARD_FINAL)
    CONSTRAINT uk_profile_rule UNIQUE (rule_type, match_value)
);

-- Quem contribui para as contas de um perfil (ex.: Familia), reconhecido pela descrição do crédito
CREATE TABLE contributor_rule (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contributor          VARCHAR(80)  NOT NULL,
    description_contains VARCHAR(120) NOT NULL,
    target_profile_id    BIGINT       NOT NULL REFERENCES profile (id)
);

-- Espelho das contas do Dinzo
CREATE TABLE dinzo_account (
    dinzo_id        VARCHAR(64)  PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    account_type    VARCHAR(20)  NOT NULL,      -- BANK | CREDIT
    sub_type        VARCHAR(30),
    tracked         BOOLEAN      NOT NULL DEFAULT TRUE,  -- false = fora dos cálculos (ex.: Carteira)
    last_synced_at  TIMESTAMP
);

-- Lançamentos espelhados do Dinzo; a chave é o id criado pelo Dinzo
CREATE TABLE ledger_entry (
    dinzo_id              VARCHAR(64)    PRIMARY KEY,
    account_id            VARCHAR(64)    NOT NULL,
    card_final            VARCHAR(8),
    entry_date            DATE           NOT NULL,
    direction             VARCHAR(10)    NOT NULL,   -- DEBIT | CREDIT
    status                VARCHAR(10)    NOT NULL,   -- PENDING | POSTED
    amount                NUMERIC(14, 2) NOT NULL,
    description           VARCHAR(500),
    original_description  VARCHAR(500),
    category_id           VARCHAR(64),
    source                VARCHAR(30)    NOT NULL,   -- OPEN_FINANCE | APP_MANUAL | ...
    installment_current   INT,
    installment_total     INT,
    recurrence_id         VARCHAR(64),
    transfer_group_id     VARCHAR(64),
    bill_to_account_id    VARCHAR(64),
    hidden_in_dinzo       BOOLEAN        NOT NULL DEFAULT FALSE,
    raw_json              TEXT           NOT NULL,
    content_hash          VARCHAR(64)    NOT NULL,
    first_seen_at         TIMESTAMP      NOT NULL,
    last_seen_at          TIMESTAMP      NOT NULL,
    changed_at            TIMESTAMP,
    removed_at            TIMESTAMP,                 -- sumiu do Dinzo na janela sincronizada

    -- Resultado do processamento local
    kind                  VARCHAR(20),               -- EXPENSE | INCOME | CONTRIBUTION | TRANSFER | BILL_PAYMENT | IGNORED
    nature                VARCHAR(10),               -- FIXED | VARIABLE
    profile_id            BIGINT REFERENCES profile (id),
    subprofile_id         BIGINT REFERENCES profile (id),
    assignment_rule       VARCHAR(40),
    contributor           VARCHAR(80),
    merged_into_id        VARCHAR(64),               -- manual consolidado no lançamento real
    superfluous           BOOLEAN                    -- decisão manual do usuário
);

CREATE INDEX ix_ledger_entry_date    ON ledger_entry (entry_date);
CREATE INDEX ix_ledger_entry_profile ON ledger_entry (profile_id, entry_date);
CREATE INDEX ix_ledger_entry_account ON ledger_entry (account_id, entry_date);

CREATE TABLE ledger_entry_tag (
    dinzo_id  VARCHAR(64)  NOT NULL REFERENCES ledger_entry (dinzo_id) ON DELETE CASCADE,
    tag       VARCHAR(80)  NOT NULL,
    PRIMARY KEY (dinzo_id, tag)
);

-- Consolidação manual -> real (Open Finance)
CREATE TABLE reconciliation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_id       VARCHAR(64)   NOT NULL REFERENCES ledger_entry (dinzo_id),
    real_id         VARCHAR(64)   NOT NULL REFERENCES ledger_entry (dinzo_id),
    score           NUMERIC(5, 3) NOT NULL,
    status          VARCHAR(20)   NOT NULL,          -- AUTO | PENDING_REVIEW | CONFIRMED | REJECTED
    created_at      TIMESTAMP     NOT NULL,
    decided_at      TIMESTAMP,
    CONSTRAINT uk_reconciliation UNIQUE (manual_id, real_id)
);
